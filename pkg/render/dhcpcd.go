package render

import (
	"slices"
	"sort"
	"strings"

	"github.com/ChevalRouting/routier/pkg/config"
)

const dhcpcdConfDest = "/etc/dhcpcd.conf"

var dhcpcdBaseLines = []string{
	"duid",
	"persistent",
	"vendorclassid",
	"option domain_name_servers, domain_name, domain_search",
	"option static_routes, classless_static_routes",
	"option interface_mtu",
	"option host_name",
	"require dhcp_server_identifier",
}

func dhcpcdManaged(cfg *config.Config) bool {
	return len(cfg.Interfaces) > 0
}

func renderDhcpcd(cfg *config.Config) ([]Output, error) {
	if !dhcpcdManaged(cfg) {
		return nil, nil
	}

	var b strings.Builder
	b.WriteString("# Generated by Routier - do not edit\n")
	for _, line := range dhcpcdBaseLines {
		b.WriteString(line)
		b.WriteString("\n")
	}

	names := make([]string, 0, len(cfg.Interfaces))
	for name := range cfg.Interfaces {
		names = append(names, name)
	}

	sort.Strings(names)
	for _, name := range names {
		iface := cfg.Interfaces[name]
		lines := dhcpcdInterfaceLines(iface)
		if len(lines) == 0 {
			continue
		}

		device := iface.Device
		if device == "" {
			device = name
		}

		b.WriteString("\ninterface ")
		b.WriteString(device)
		b.WriteString("\n")
		for _, line := range lines {
			b.WriteString("  ")
			b.WriteString(line)
			b.WriteString("\n")
		}
	}

	return []Output{{Name: "dhcpcd/dhcpcd.conf", Dest: dhcpcdConfDest, Content: b.String()}}, nil
}

func dhcpcdInterfaceLines(iface *config.Interface) []string {
	var lines []string
	if slices.Contains(iface.Addresses, "slaac") && !slices.Contains(iface.Addresses, "dhcp6") {
		lines = append(lines, "noipv6rs")
	}

	lines = append(lines, iface.DHCPOptions...)
	return lines
}
